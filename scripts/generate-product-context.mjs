import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

const locales = [
  "bg",
  "de",
  "en",
  "es",
  "fr",
  "he",
  "it",
  "ka",
  "pl",
  "pt",
  "ru",
  "sr",
  "tr",
  "uk",
];

const productSections = [
  "about",
  "free_page",
  "plus",
  "paywall",
  "contact_page",
  "settings",
];

const rootKeys = [
  "terms_title",
  "terms_paragraph1",
  "terms_paragraph2",
  "terms_paragraph3",
  "privacy_title",
  "privacy_paragraph1",
  "privacy_paragraph2",
  "start_subtitle",
  "start_description",
  "quick_check_title",
  "quick_check_duration",
  "full_consultation_title",
  "full_consultation_description",
];

const sourceFiles = [
  "app/about.tsx",
  "app/free.tsx",
  "app/paywall.tsx",
  "app/plus.tsx",
  "app/settings.tsx",
  "app/terms-screen.tsx",
  "components/TermsModal.tsx",
  "i18n.ts",
  "app.json",
  "package.json",
  ...locales.map((locale) => `locales/${locale}.json`),
];

const codeSourceFiles = sourceFiles.filter(
  (file) => file.endsWith(".ts") || file.endsWith(".tsx")
);

function readJson(relativePath) {
  const absolutePath = path.join(root, relativePath);

  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing source file: ${relativePath}`);
  }

  return JSON.parse(fs.readFileSync(absolutePath, "utf8"));
}

function readText(relativePath) {
  const absolutePath = path.join(root, relativePath);

  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing source file: ${relativePath}`);
  }

  return fs.readFileSync(absolutePath, "utf8");
}

function getValue(object, keyPath) {
  return keyPath.split(".").reduce(
    (value, key) =>
      value && typeof value === "object"
        ? value[key]
        : undefined,
    object
  );
}

function extractStaticI18nKeys(source) {
  const keys = new Set();
  const pattern =
    /\bi18n\.t\(\s*["'`]([^"'`$]+)["'`]\s*\)/g;

  for (const match of source.matchAll(pattern)) {
    keys.add(match[1]);
  }

  return [...keys].sort();
}

function pickProductContext(data) {
  const result = {};

  for (const section of productSections) {
    if (data[section] !== undefined) {
      result[section] = data[section];
    }
  }

  for (const key of rootKeys) {
    if (data[key] !== undefined) {
      result[key] = data[key];
    }
  }

  return result;
}

for (const sourceFile of sourceFiles) {
  const absolutePath = path.join(root, sourceFile);

  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing product source: ${sourceFile}`);
  }
}

const usedI18nKeysByFile = Object.fromEntries(
  codeSourceFiles.map((sourceFile) => [
    sourceFile,
    extractStaticI18nKeys(readText(sourceFile)),
  ])
);

const usedI18nKeys = [
  ...new Set(
    Object.values(usedI18nKeysByFile).flat()
  ),
].sort();

const uiTextByLocale = Object.fromEntries(
  locales.map((locale) => {
    const data = readJson(`locales/${locale}.json`);
    const values = {};

    for (const key of usedI18nKeys) {
      const value = getValue(data, key);

      if (typeof value === "string" && value.trim()) {
        values[key] = value.trim();
      }
    }

    return [locale, values];
  })
);

const localizedContext = Object.fromEntries(
  locales.map((locale) => {
    const data = readJson(`locales/${locale}.json`);

    return [
      locale,
      pickProductContext(data),
    ];
  })
);

const output = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),

  supportedLocales: locales,

  sourceFiles,
  usedI18nKeysByFile,
  uiTextByLocale,

  productBoundaries: {
    medicalQuestionsUseConsultationFlow: true,
    doesNotDiagnose: true,
    doesNotPrescribeTreatment: true,
    doesNotReplaceVeterinaryExamination: true,
    photosAndVideosSupportedInConsultation: false,
  },

  locales: localizedContext,
};

const outputPath = path.join(
  root,
  "cloudflare/agent-worker/mamascota-agent/src/product/productContext.generated.ts"
);

fs.writeFileSync(
  outputPath,
  [
    "// Generated by scripts/generate-product-context.mjs.",
    "// Do not edit manually.",
    "",
    `export const PRODUCT_CONTEXT = ${JSON.stringify(output, null, 2)} as const;`,
    "",
  ].join("\n"),
  "utf8"
);

console.log(
  `Generated: ${path.relative(root, outputPath)}`
);
console.log(`Locales: ${locales.length}`);
console.log(`Source files: ${sourceFiles.length}`);
